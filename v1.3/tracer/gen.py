#!/usr/bin/env python3
"""Encode the Tracer's division-family templates (templates.py) as 128-bit expansion words (spec 4.19.3).

Writes, under out/:
  div_templates.tracer.hex    the Tracer's words: one line per word, "<template> <index> <hex128>"
  div_templates.replayer.hex  the same templates with the untraced rows removed: what the replayer's ROM holds
  div_templates.inc           a C++ table of the Tracer's words, for harness/check_div.cpp
  div_templates.md            a readable listing

Conventions (the open ones are WORKER7/QUESTIONS.md Q3-Q5):
  - seq_remaining counts every word of the Tracer's template, traced or untraced (Q4);
  - rd0 is written in the template's first word, whichever kind it is (Q4);
  - advice_reg [62:56] holds the bank-1 index, code - 128, so codes 146-255 give 18-127 (Q3);
  - virt is set on every word whose opcode isn't the source instruction's; report_c on the last word only;
  - untraced words carry no virt, report_c or from_log.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from templates import OP, TEMPLATES, RD0, FORMAT_R  # noqa: E402

SRC = {'RD': 129, 'RS1': 130, 'RS2': 131}


def code(sym):
    if sym in SRC:
        return SRC[sym]
    if sym == 'x0':
        return 0
    if sym == 'K':
        return 128
    if sym[0] == 't':
        k = int(sym[1:])
        assert 0 <= k <= 7
        return 137 + k
    if sym[0] == 'b':
        k = int(sym[1:])
        assert 0 <= k <= 109
        return 146 + k
    raise ValueError(sym)


def encode(row, seq_remaining, first, last, src_op, rd0):
    op = OP[row['op']]
    w = op | code(row['rd']) << 8 | code(row['rs1']) << 16 | code(row['rs2']) << 24
    w |= seq_remaining << 32
    if first:
        w |= rd0 << 46
    w |= FORMAT_R << 48
    if not row['untraced']:
        if row['op'] != src_op:
            w |= 1 << 51                      # virt
        if last:
            w |= 1 << 53                      # report_c
        if row['advice'] is not None:
            w |= 1 << 54                      # from_log
            c = code(row['advice'])
            assert 146 <= c <= 255, 'advice_reg must name a bank-1 register'
            w |= (c - 128) << 56              # advice_reg
    else:
        assert 146 <= code(row['rd']) <= 255, 'an untraced row writes bank 1 only'
        w |= 1 << 55                          # untraced
    w |= (row['const'] & (2**64 - 1)) << 64
    return w


def words(name, rows):
    n = len(rows)
    assert not rows[-1]['untraced'], 'a template never ends with an untraced row'
    return [encode(r, n - 1 - i, i == 0, i == n - 1, name, RD0[name]) for i, r in enumerate(rows)]


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out')
    os.makedirs(out, exist_ok=True)
    tr, rp, md, inc = [], [], [], []
    md.append('# The Tracer\'s division-family templates (generated by gen.py; do not edit)\n')
    md.append('| template | words (Tracer) | of which untraced | words (replayer) |')
    md.append('|---|---|---|---|')
    summary = []
    for name, rows in TEMPLATES.items():
        tw = words(name, rows)
        traced = [r for r in rows if not r['untraced']]
        rw = words(name, [dict(r, advice=None) for r in traced])
        # The replayer's advice row has from_log but no advice_reg (it ignores the field; 0 here).
        rw = [w | (1 << 54) if r['advice'] is not None else w for w, r in zip(rw, traced)]
        for i, w in enumerate(tw):
            tr.append(f'{name} {i} {w:032x}')
        for i, w in enumerate(rw):
            rp.append(f'{name} {i} {w:032x}')
        summary.append(f'| {name} | {len(tw)} | {len(tw) - len(rw)} | {len(rw)} |')
        inc.append(f'  {{"{name}", isa::{name}, {len(tw)}, {{' +
                   ', '.join(f'{{0x{w & (2**64 - 1):016x}ull, 0x{w >> 64:016x}ull}}' for w in tw) + '}},')
    md += summary
    md.append(f'| **total** | **{sum(len(r) for r in TEMPLATES.values())}** | '
              f'**{sum(r["untraced"] for rows in TEMPLATES.values() for r in rows)}** | '
              f'**{sum(not r["untraced"] for rows in TEMPLATES.values() for r in rows)}** |\n')
    for name, rows in TEMPLATES.items():
        md.append(f'## {name}\n')
        md.append('| # | kind | row | word |')
        md.append('|---|---|---|---|')
        for i, (r, w) in enumerate(zip(rows, words(name, rows))):
            kind = 'untraced' if r['untraced'] else ('advice' if r['advice'] else 'traced')
            extra = f' ← {r["advice"]}' if r['advice'] else ''
            md.append(f'| {i} | {kind} | `{r["op"]} {r["rd"]}, {r["rs1"]}, {r["rs2"]}`{extra} | `{w:032x}` |')
        md.append('')
    open(os.path.join(out, 'div_templates.tracer.hex'), 'w').write('\n'.join(tr) + '\n')
    open(os.path.join(out, 'div_templates.replayer.hex'), 'w').write('\n'.join(rp) + '\n')
    open(os.path.join(out, 'div_templates.md'), 'w').write('\n'.join(md))
    maxw = max(32, max(len(r) for r in TEMPLATES.values()))  # room for mutants (harness/mutants.py)
    open(os.path.join(out, 'div_templates.inc'), 'w').write(
        '// Generated by wip/tracer/gen.py from templates.py; do not edit.\n'
        f'constexpr int kMaxWords = {maxw};\n'
        'struct Word128 { u64 lo, hi; };\n'
        'struct TracerTemplate { const char* name; isa::OpCode src; int n; Word128 w[kMaxWords]; };\n'
        'static const TracerTemplate kTemplates[] = {\n' + '\n'.join(inc) + '\n};\n'
        + ''.join(f'static_assert((int)isa::{k} == {v});\n' for k, v in OP.items()))
    print('\n'.join(summary))


if __name__ == '__main__':
    main()
