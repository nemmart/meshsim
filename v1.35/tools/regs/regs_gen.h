    PERIPHERAL_STD_MEMBERS;
    MESH_RW RUN_CONFIG;       /* 32: [23:0] rows, [24] store log, [25] rd_prev, [28:26] Tracer's (ignored); sticky, 0 at reset */
    MESH_RO ROWS_RUN;         /* 33: rows of this pass completed, 24 bits */
