import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Collects the per-run CSVs of SortTest (written by the P4 kit's run.sh) into one Markdown summary and one CSV.
 * Labels: p4/<set> (the measurement), shuf/<set> (the same run, shuffled child order: must be identical), sweep/<set>/<point>
 * (the whole-sort sensitivity sweep). Usage: java SortSummary <dir> [out.md]; writes <dir>/all.csv too.
 * An Inputs section checks every run's "inputs:" log line against HASHES (or -Dsort.hashes=FILE) and the runs against each
 * other (Inputs.java).
 */
final class SortSummary {
    record Run(String label, String fmt, String path, String params, int ready, long seed, Map<String, Long> steps, long total, int failed, String file) {}

    public static void main(String[] a) throws IOException {
        Path dir = Path.of(a.length > 0 ? a[0] : "results");
        List<Run> runs = new ArrayList<>();
        StringBuilder all = new StringBuilder();
        List<Path> files;
        try (var st = Files.list(dir)) { files = st.filter(p -> p.toString().endsWith(".csv") && !p.toString().endsWith(".phases.csv") && !p.getFileName().toString().equals("all.csv")).sorted().toList(); }
        List<String> missing = new ArrayList<>();
        for (Path f : files) {
            List<String> ls = Files.readAllLines(f);
            if (ls.size() < 2) { missing.add(f.getFileName().toString()); continue; }
            if (all.length() == 0) all.append("file,").append(ls.get(0)).append('\n');
            Map<String, Long> steps = new LinkedHashMap<>(); long total = -1; String[] h = null; int failed = 0;
            for (String l : ls.subList(1, ls.size())) {
                all.append(f.getFileName()).append(',').append(l).append('\n');
                String[] c = l.split(",", -1); h = c;
                failed = Math.max(failed, c[19].isEmpty() ? 0 : Integer.parseInt(c[19]));
                if (c[9].equals("TOTAL")) total = Long.parseLong(c[10]); else steps.merge(c[9], Long.parseLong(c[10]), Long::sum);
            }
            runs.add(new Run(h[0], h[1], h[6], h[5], Integer.parseInt(h[4]), Long.parseLong(h[3]), steps, total, failed, f.getFileName().toString()));
        }
        // logs without a CSV: runs that failed or have not finished
        try (var st = Files.list(dir)) {
            for (Path l : st.filter(p -> p.toString().endsWith(".log")).sorted().toList()) {
                String id = l.getFileName().toString().replace(".log", "");
                if (!Files.exists(dir.resolve(id + ".csv"))) missing.add(id + " (log, no CSV: crashed, failed to finish or still running)");
            }
        }
        StringBuilder md = new StringBuilder("# Sort measurements: summary of " + dir + "\n\n");
        md.append("Generated by SortSummary from ").append(runs.size()).append(" runs. Cycles are GO of L1 -> all READY of L2 [meas: SortTest].\n\n");
        int flagged = inputs(dir, runs, md);

        // ---- P4
        md.append("## P4: every data set, both formats\n\n| set | format | path | total | L1 | SPLIT | XB + RED | skew planning (XC TH SWEEP DESC) | keys (K, K1.*, K2.*) | values (V, V1.*, V2.*) | L2 | empty and other | checks failed |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n");
        Map<String, Run> p4 = new TreeMap<>();
        for (Run r : runs) if (r.label().startsWith("p4/")) p4.put(r.label().substring(3) + " " + r.fmt(), r);
        for (Run r : p4.values()) {
            long l1 = g(r, "L1"), sp = g(r, "SPLIT"), xr = g(r, "XB") + g(r, "RED"), plan = 0, keys = 0, vals = 0, l2 = g(r, "L2"), other = 0;
            for (var e : r.steps().entrySet()) {
                String n = e.getKey(); long v = e.getValue();
                if (n.matches("L1|SPLIT|XB|RED|L2")) continue;
                if (v <= 150 && n.matches("XC|TH|SWEEP|DESC|K|V|..\\..")) { other += v; continue; }
                if (n.matches("XC|TH|SWEEP|DESC")) plan += v;
                else if (n.equals("K") || n.startsWith("K1.") || n.startsWith("K2.")) keys += v;
                else if (n.equals("V") || n.startsWith("V1.") || n.startsWith("V2.")) vals += v;
                else other += v;
            }
            md.append(String.format("| %s | %s | %s | %,d | %,d | %,d | %,d | %,d | %,d | %s | %,d | %,d | %d |%n", r.label().substring(3), r.fmt(), r.path(), r.total(),
                l1, sp, xr, plan, keys, r.fmt().equals("k128") ? String.format("%,d", vals) : "-", l2, other, r.failed()));
        }

        // ---- shuffled
        md.append("\n## Shuffled child order (must equal the fixed-order run step by step)\n\n| set | format | seed | total | fixed-order total | identical |\n|---|---|---|---|---|---|\n");
        for (Run r : runs) if (r.label().startsWith("shuf/")) {
            Run f = p4.get(r.label().substring(5) + " " + r.fmt());
            md.append(String.format("| %s | %s | %d | %,d | %s | %s |%n", r.label().substring(5), r.fmt(), r.seed(), r.total(),
                f == null ? "(missing)" : String.format("%,d", f.total()), f == null ? "?" : f.steps().equals(r.steps()) && f.total() == r.total() ? "yes" : "**NO**"));
        }

        // ---- sweep
        Map<String, List<Run>> sw = new TreeMap<>();
        for (Run r : runs) if (r.label().startsWith("sweep/")) sw.computeIfAbsent(r.label().split("/")[1] + " " + r.fmt(), x -> new ArrayList<>()).add(r);
        for (var e : sw.entrySet()) {
            Run def = e.getValue().stream().filter(r -> r.label().endsWith("/default")).findFirst().orElse(null);
            md.append("\n## Sweep: " + e.getKey() + "\n\n| point | parameters | ready_latency | path | total | delta | delta % | checks failed |\n|---|---|---|---|---|---|---|---|\n");
            long lo = Long.MAX_VALUE, hi = Long.MIN_VALUE;
            List<Run> rs = new ArrayList<>(e.getValue()); rs.sort((x, y) -> x.label().compareTo(y.label()));
            for (Run r : rs) {
                long d = def == null ? 0 : r.total() - def.total();
                if (r.failed() == 0) { lo = Math.min(lo, r.total()); hi = Math.max(hi, r.total()); }
                md.append(String.format("| %s | %s | %d | %s | %,d | %+,d | %+.2f %% | %d |%n", r.label().substring(r.label().lastIndexOf('/') + 1), r.params(), r.ready(), r.path(), r.total(), d,
                    def == null ? 0.0 : 100.0 * d / def.total(), r.failed()));
            }
            if (def != null && lo <= hi) md.append(String.format("%nBand over the points without a failed check: %,d .. %,d against %,d (%+.2f %% .. %+.2f %%).%n",
                lo, hi, def.total(), 100.0 * (lo - def.total()) / def.total(), 100.0 * (hi - def.total()) / def.total()));
        }
        if (!missing.isEmpty()) { md.append("\n## Runs with no result\n\n"); for (String m : missing) md.append("- ").append(m).append('\n'); }
        Files.writeString(dir.resolve("all.csv"), all.toString());
        Path out = a.length > 1 ? Path.of(a[1]) : dir.resolve("SUMMARY.md");
        Files.writeString(out, md.toString());
        System.out.println("wrote " + out + " and " + dir.resolve("all.csv") + " (" + runs.size() + " runs" + (missing.isEmpty() ? "" : ", " + missing.size() + " without a result")
            + (flagged == 0 ? "" : "; WARNING: " + flagged + " runs flagged under Inputs") + ")");
    }

    /** The Inputs section. Each run's log starts with SortTest's "inputs:" line (Inputs.java); the runs
     *  are compared with the reference set (HASHES in the working directory, or -Dsort.hashes=FILE) and with each other.
     *  Flags: a file whose hash differs from the reference, a log with no inputs line (an older kit), and a directory
     *  whose runs used more than one jar or image. Returns the number of runs flagged. */
    static int inputs(Path dir, List<Run> runs, StringBuilder md) throws IOException {
        Path hf = Path.of(System.getProperty("sort.hashes", "HASHES"));
        Map<String, String> ref = Files.exists(hf) ? Inputs.readHashes(hf) : null;
        List<String> noLine = new ArrayList<>(), differ = new ArrayList<>();
        Map<String, List<String>> kits = new TreeMap<>();       // jar + image hashes -> runs
        int keysChecked = 0;
        for (Run r : runs) {
            String id = r.file().substring(0, r.file().length() - 4);
            Path log = dir.resolve(id + ".log");
            Map<String, String> h = null;
            if (Files.exists(log)) for (String l : Files.readAllLines(log)) if ((h = Inputs.parse(l)) != null) break;
            if (h == null) { noLine.add(id); continue; }
            StringBuilder kit = new StringBuilder();
            for (var e : h.entrySet()) if (e.getKey().equals("meshsim.jar") || e.getKey().startsWith("image/") || e.getKey().equals("hops.txt"))
                kit.append(e.getKey()).append(' ').append(Inputs.abbrev(e.getValue())).append(", ");
            kits.computeIfAbsent(kit.toString(), x -> new ArrayList<>()).add(id);
            if (ref != null) {
                for (String k : h.keySet()) if (k.endsWith(".keys") && ref.containsKey(k)) keysChecked++;
                List<String> d = Inputs.differences(h, ref);
                if (!d.isEmpty()) differ.add(id + ": " + String.join("; ", d));
            }
        }
        md.append("## Inputs\n\n");
        int withLine = runs.size() - noLine.size();
        if (ref == null) md.append("No reference set (").append(hf).append(" not found): the runs are compared only with each other.\n");
        else if (differ.isEmpty() && withLine > 0) md.append(String.format("All %d runs with an inputs line read the reference inputs (%s): jar, image and hops.txt, and %d key files.%n", withLine, hf, keysChecked));
        if (!differ.isEmpty()) {
            md.append(String.format("**%d runs read files that differ from the reference set (%s); their results are not comparable with the reference's:**%n%n", differ.size(), hf));
            for (String d : differ) md.append("- ").append(d).append('\n');
        }
        if (kits.size() > 1) {
            md.append(String.format("%n**The runs used %d different kits (jar, image, hops.txt):**%n%n", kits.size()));
            for (var e : kits.entrySet()) md.append("- ").append(e.getValue().size()).append(" runs (").append(e.getValue().get(0)).append(e.getValue().size() > 1 ? ", ..." : "")
                .append("): ").append(e.getKey().replaceAll(", $", "")).append('\n');
        }
        if (!noLine.isEmpty()) {
            md.append(String.format("%n**%d runs have no inputs line (a kit before M9, or no log); their inputs are unknown:** %s%n", noLine.size(),
                String.join(", ", noLine.size() > 8 ? noLine.subList(0, 8) : noLine) + (noLine.size() > 8 ? ", ..." : "")));
        }
        md.append('\n');
        java.util.Set<String> f = new java.util.TreeSet<>();
        for (String d : differ) f.add(d.substring(0, d.indexOf(": ")));
        if (kits.size() > 1) for (Run r : runs) f.add(r.file().substring(0, r.file().length() - 4));
        f.addAll(noLine);
        return f.size();
    }
    static long g(Run r, String k) { return r.steps().getOrDefault(k, 0L); }
}
