    b += "\n/* sizes (link word [161:160]); modes (3.1); counters */\n";
    def(b, "SIZE_32", u(SIZE_32), nullptr); def(b, "SIZE_64", u(SIZE_64), nullptr); def(b, "SIZE_128", u(SIZE_128), nullptr);
